/* node tools/fetch-prices.mjs (npm run prices) - real-life card prices, from
   TCGdex's TCGplayer snapshot (docs/cards.md, Prices).

   Writes src/data/cards/prices.js: PRICED_AT (the snapshot's day) and PRICES,
   { setId: { localId: [normal, holo, reverse] } } in US cents, 0 where
   TCGplayer has no market price for that printing. DISPLAY ONLY: a price
   never reaches a rule module, a sale or dust (asserted) - it is what the
   card is worth on the table, not in the game. Loaded lazily by
   ui/cards/load.js alone.

   Always fetched fresh (a price is a day's), never from fetch-cards' cache.
   Base Set is skipped: the packs here are its 1st Edition and TCGplayer's
   price through TCGdex is the unlimited print's - a wrong number is worse
   than none. */

import { writeFileSync, readdirSync } from "node:fs";

const ROOT = new URL("../", import.meta.url);
const API = "https://api.tcgdex.net/v2/en";
const SKIP = new Set(["base1"]);
const KEY = { n: "normal", h: "holofoil", r: "reverse-holofoil" };

async function get(url) {
  for (let i = 0; ; i++) {
    try {
      const r = await fetch(url);
      if (r.status === 404) return null;
      if (!r.ok) throw new Error(`HTTP ${r.status}`);
      return await r.json();
    } catch (e) {
      if (i >= 4) throw new Error(`${url}: ${e.message}`);
      await new Promise((ok) => setTimeout(ok, 500 * (i + 1)));
    }
  }
}
async function pool(items, n, fn) {
  const out = new Array(items.length); let next = 0;
  await Promise.all(Array.from({ length: n }, async () => { while (next < items.length) { const i = next++; out[i] = await fn(items[i]); } }));
  return out;
}
const cents = (p) => Math.round(((p?.marketPrice ?? p?.midPrice) || 0) * 100);

const PRICES = {};
let day = "";
for (const file of readdirSync(new URL("src/data/cards/sets/", ROOT)).sort()) {
  const { SET, CARDS } = await import(new URL(`src/data/cards/sets/${file}`, ROOT));
  if (SKIP.has(SET.id)) continue;
  const rows = await pool(CARDS, 6, async ([localId]) => {
    // A gallery card is asked by its subset's id (swsh9tg-TG01).
    const sub = SET.subs?.[localId.replace(/\d+$/, "")];
    const tp = (await get(`${API}/cards/${sub ?? SET.id}-${localId}`))?.pricing?.tcgplayer;
    if (tp?.updated > day) day = tp.updated;
    return [localId, ["n", "h", "r"].map((v) => cents(tp?.[KEY[v]]))];
  });
  const set = {};
  for (const [id, p] of rows) if (p.some(Boolean)) set[id] = p;
  PRICES[SET.id] = set;
  console.log(`${SET.id}: ${Object.keys(set).length} of ${CARDS.length} priced`);
}

writeFileSync(new URL("src/data/cards/prices.js", ROOT), `/* GENERATED by tools/fetch-prices.mjs (npm run prices) - TCGplayer market
   prices through TCGdex, US cents per printing [normal, holo, reverse].
   Display only (docs/cards.md, Prices). */
export const PRICED_AT = ${JSON.stringify(day.slice(0, 10))};
export const PRICES = ${JSON.stringify(PRICES)};
`.replace(/\n/g, "\r\n"));
