// Gender ratios and the female looks (2026-10-15, the late-game shortlist's
// gender-differences phase). PokeAPI's species say how many eighths of a
// species are female (-1: genderless) and whether the female LOOKS different;
// for those, the female sprite (and its shiny) is fetched from the SAME art
// set the ordinary sprite came from (fetch-species' `artFor`) and from no
// other. FireRed (1-386) drew no gender differences - they began in Gen 4 -
// and HGSS's female beside a FireRed male was a different pose and size, so
// 1-386 have no female look (your call, 2026-10-15): their mark, not a
// picture. A set with no female sprite gives no look either. Writes
// public/sprites/female/<id>.png, public/sprites/shiny/female/<id>.png and
// src/data/genders.js. Cached in .assets-src/genders.
//
//   npm run genders
import { mkdirSync, existsSync, readFileSync, writeFileSync, rmSync } from "node:fs";

const API = "https://pokeapi.co/api/v2";
const GH = "https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon";
const HGSS = `${GH}/versions/generation-iv/heartgold-soulsilver`;
const BW = `${GH}/versions/generation-v/black-white`;
const CACHE = ".assets-src/genders";
mkdirSync(CACHE, { recursive: true });
// Written whole each run, so a look the rules drop leaves no file behind.
for (const d of ["public/sprites/female", "public/sprites/shiny/female"]) {
  rmSync(d, { recursive: true, force: true });
  mkdirSync(d, { recursive: true });
}

async function cached(file, url, binary) {
  const path = `${CACHE}/${file}`;
  if (existsSync(path)) return binary ? readFileSync(path) : JSON.parse(readFileSync(path, "utf8"));
  if (existsSync(`${path}.none`)) return null;
  const res = await fetch(url);
  if (res.status === 404) { writeFileSync(`${path}.none`, ""); return null; }
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  if (binary) { const b = Buffer.from(await res.arrayBuffer()); writeFileSync(path, b); return b; }
  const j = await res.json();
  const keep = { gender_rate: j.gender_rate, has_gender_differences: j.has_gender_differences };
  writeFileSync(path, JSON.stringify(keep));
  return keep;
}

// The set an ordinary sprite came from; FireRed's (1-386) has no female art.
const setsFor = (id) => (id <= 386 ? [] : id <= 493 ? [HGSS] : id <= 649 ? [BW] : [GH]);
async function femaleArt(id, where) {
  for (const set of setsFor(id)) {
    const b = await cached(`${where.replace("/", "-")}${id}-${set === GH ? "gh" : set === BW ? "bw" : "hgss"}.png`,
      `${set}/${where}female/${id}.png`, true);
    if (b) return b;
  }
  return null;
}

const rate = {};
const female = [];
const femaleShiny = [];
for (let id = 1; id <= 1025; id++) {
  const sp = await cached(`${id}.json`, `${API}/pokemon-species/${id}`);
  rate[id] = sp.gender_rate;
  if (!sp.has_gender_differences) continue;
  const art = await femaleArt(id, "");
  if (!art) continue;
  writeFileSync(`public/sprites/female/${id}.png`, art);
  female.push(id);
  const shiny = await femaleArt(id, "shiny/");
  if (shiny) { writeFileSync(`public/sprites/shiny/female/${id}.png`, shiny); femaleShiny.push(id); }
}

// Eighths female per dex id; -1 genderless. Only ids that are not 4 (even)
// are written, so the file stays small - `RATE_OF` reads a missing id as 4.
const odd = Object.fromEntries(Object.entries(rate).filter(([, r]) => r !== 4));
writeFileSync("src/data/genders.js", [
  "// Generated by tools/fetch-genders.mjs (npm run genders) - do not edit.",
  "// Eighths of a species that are female (-1: genderless); an id not listed is 4.",
  `export const FEMALE_EIGHTHS = ${JSON.stringify(odd)};`,
  "// Species whose female LOOKS different, with art of her own (and her shiny).",
  `export const FEMALE_ART = new Set(${JSON.stringify(female)});`,
  `export const FEMALE_SHINY = new Set(${JSON.stringify(femaleShiny)});`,
  "",
].join("\r\n"));
console.log(`genders: ${female.length} female looks (${femaleShiny.length} shiny), ${Object.values(rate).filter((r) => r === -1).length} genderless`);
