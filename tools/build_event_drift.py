"""An event poster's sky (npm run drift).

The announcement of a dated event (ui/Season.jsx `SeasonIntro`) draws a sky
over its title, and in it its Pokemon float across - Haunter and Duskull over
The Haunting, Mew and Rayquaza over the Poncho Parade (asked for, 2026-10-29:
"use the pokemon animations from arena"). Each is the Arena's own PMD Walk,
cut out of the shipped atlas (public/arena/pmd, npm run pmd) into one small
animated PNG at native pixels, as build_arena_intro.py does for the Arena's
announcement. The ids are each event's `drift` (eventforms.js).

Facing RIGHT always (`<id>.png`), and LEFT (`<id>-l.png`) only where PMD's
artist drew the left-facing walk: a left row PMD stores as the right one
mirrored is no drawing, and a flat CSS mirror read as the sprite flipping
(reported, 2026-10-29: "if there's none then don't flip them"). Which ids have
one is written to src/data/drift.js (`DRIFT_LEFT`), which the poster reads to
send only those leftward. Re-run after npm run pmd.
"""
import json
import re
from pathlib import Path

from build_arena_intro import bake

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "public" / "events" / "drift"
PMD = ROOT / "public" / "arena" / "pmd"
FORMS = ROOT / "src" / "data" / "eventforms.js"
DATA = ROOT / "src" / "data" / "drift.js"
RIGHT, LEFT = 2, 6           # PMD's direction rows


def drawn_left(dex):
    """True when the atlas stores the left-facing walk as its own frames, not a mirror (-1-k)."""
    meta = json.loads((PMD / f"{dex}.json").read_text())
    return not isinstance(meta["a"]["Walk"]["r"][LEFT], int)


if __name__ == "__main__":
    ids = sorted({int(n) for m in re.finditer(r"drift: \[([\d, ]+)\]", FORMS.read_text(encoding="utf-8"))
                  for n in m.group(1).split(",")})
    left = [d for d in ids if drawn_left(d)]
    for dex in ids:
        bake(str(dex), dex, "Walk", RIGHT, out=OUT, rest=0)
    for dex in left:
        bake(f"{dex}-l", dex, "Walk", LEFT, out=OUT, rest=0)
    # A body no event names any more is gone, and so is a left one no longer drawn.
    keep = {str(d) for d in ids} | {f"{d}-l" for d in left}
    for f in OUT.glob("*.png"):
        if f.stem not in keep:
            f.unlink()
    DATA.write_text(
        "/* GENERATED by tools/build_event_drift.py (npm run drift) - the poster sky's Pokemon\r\n"
        "   whose LEFT-facing walk PMD's artist drew (public/events/drift/<id>-l.png): only these\r\n"
        "   fly leftward; the rest fly right, never mirrored. */\r\n"
        f"export const DRIFT_LEFT = {json.dumps(left)};\r\n", encoding="utf-8", newline="")
    print(f"{len(ids)} drifting bodies, {len(left)} drawn facing left")
