# -*- coding: utf-8 -*-
"""RETRO ORIGINS: our own Game Boy Color-style drawings, for the species whose
debut art IS their ordinary art (Hoenn on - see build_origin.py's DEBUT).

Run:  npm run retro      (python tools/build_retro.py)

Each drawing is `art/origin/<dex id>.png|jpg` - a sprite drawn for this game
from reports/Origin retro prompts.md, on a plain white background. It is keyed
the way an event costume is (build_event_sprites.py: the border flood, then one
target pixel per block, the outline thinned to one pixel), framed on the
species' own canvas, and held to an OLD palette (PALETTE colours plus the
outline) - the tell that makes an Origin an Origin. The output is
`public/sprites/origin/<id>.png`, and `src/data/retro.js` lists the ids that
have one: `hasOrigin` reads it, so a drawing added is a species that can wear
Origin again, and nothing else changes.

Hoenn on wore SageDeoxys' sprites until 2026-10-28: he did not approve their
use, so they were removed, and this replaces them one drawing at a time."""

import glob
import io
import json
import os
import sys

import numpy as np
from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_event_sprites import key, shrink, thin  # noqa: E402  (the same keying as a costume)
from build_origin import sources_for  # noqa: E402

ART = os.path.join(ROOT, "art", "origin")
SPRITES = os.path.join(ROOT, "public", "sprites")
OUT = os.path.join(SPRITES, "origin")
# An old sprite's colours: Gen 1 and 2 art uses 4, build_origin.py's bound is 7.
PALETTE = 6


def retro(img):
    """Fewer colours, transparency kept: the median cut over the opaque pixels."""
    a = img.convert("RGBA")
    alpha = a.getchannel("A")
    q = a.convert("RGB").quantize(colors=PALETTE, method=Image.Quantize.MEDIANCUT).convert("RGBA")
    q.putalpha(alpha)
    return q


def build(path):
    dex_id = int(os.path.splitext(os.path.basename(path))[0])
    if dex_id >= 10000 or sources_for(dex_id) is not None:
        sys.exit("%s: #%d has older art of its own (or is a form) - only Hoenn on is drawn" % (path, dex_id))
    base = Image.open(os.path.join(SPRITES, "%d.png" % dex_id)).convert("RGBA")
    a = np.asarray(Image.open(path).convert("RGB"))
    out = retro(thin(shrink(a, key(a), base)))
    assert out.size == base.size
    out.save(os.path.join(OUT, "%d.png" % dex_id), optimize=True)
    colours = len({px[:3] for px in out.getdata() if px[3] > 40})
    print("#%d: %dpx, %d colours" % (dex_id, out.size[0], colours))
    return dex_id


if __name__ == "__main__":
    os.makedirs(ART, exist_ok=True)
    os.makedirs(OUT, exist_ok=True)
    files = sorted(glob.glob(os.path.join(ART, "*.png")) + glob.glob(os.path.join(ART, "*.jpg")))
    made = sorted({build(f) for f in files})
    # A retro Origin whose drawing is gone is gone too: the file names the art.
    for name in os.listdir(OUT):
        n = int(name[:-4]) if name[:-4].isdigit() else None
        if n is not None and sources_for(n) is None and n < 10000 and n not in made:
            os.remove(os.path.join(OUT, name))
    io.open(os.path.join(ROOT, "src", "data", "retro.js"), "w", encoding="utf-8", newline="\r\n").write(
        "/* GENERATED by tools/build_retro.py - the species after Johto whose Origin\n"
        "   is our own retro drawing (art/origin). */\n"
        "export const RETRO_IDS = new Set(%s);\n" % json.dumps(made, separators=(",", ":")))
    print("%d retro Origins" % len(made))
