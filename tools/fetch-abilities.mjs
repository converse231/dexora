/* ABILITIES (npm run abilities): every species' abilities from PokeAPI, for
   the walking party's field abilities (src/game/abilities.js). Our species
   names ARE PokeAPI's pokemon names, forms included, so each is one request.

   Writes src/data/abilities.js: ABILITY_NAMES (slugs, once each) and
   ABILITIES, id -> [[regular ability indices], hidden index or -1].
   Cached in .assets-src/abilities/ so a re-run is offline. */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";

const API = "https://pokeapi.co/api/v2";
const CACHE = new URL("../.assets-src/abilities/", import.meta.url);
mkdirSync(CACHE, { recursive: true });
const { SPECIES } = await import("../src/data/dex.js");

async function get(name) {
  const f = new URL(`${name}.json`, CACHE);
  if (existsSync(f)) return JSON.parse(readFileSync(f, "utf8"));
  let r = await fetch(`${API}/pokemon/${name}`);
  /* A species whose default form carries a suffix (deoxys is deoxys-normal):
     its species record names the default variety. */
  if (r.status === 404) {
    const s = await fetch(`${API}/pokemon-species/${name}`);
    const def = s.ok ? (await s.json()).varieties?.find((v) => v.is_default)?.pokemon?.name : null;
    if (!def) return null;
    r = await fetch(`${API}/pokemon/${def}`);
  }
  if (r.status === 404) return null;
  if (!r.ok) throw new Error(`${name}: ${r.status}`);
  const j = await r.json();
  const keep = { abilities: j.abilities.map((a) => ({ name: a.ability.name, hidden: a.is_hidden })) };
  writeFileSync(f, JSON.stringify(keep));
  return keep;
}

const out = new Map();
const missing = [];
let next = 0;
await Promise.all(Array.from({ length: 12 }, async () => {
  while (next < SPECIES.length) {
    const sp = SPECIES[next++];
    const j = await get(sp.name);
    if (j?.abilities?.length) out.set(sp.id, j.abilities);
    else missing.push(sp.name);
  }
}));

const names = [...new Set([...out.values()].flat().map((a) => a.name))].sort();
const idx = new Map(names.map((n, i) => [n, i]));
const rows = {};
for (const sp of SPECIES) {
  const a = out.get(sp.id);
  if (!a) continue;
  const regular = a.filter((x) => !x.hidden).map((x) => idx.get(x.name));
  const hidden = a.find((x) => x.hidden);
  rows[sp.id] = [regular.length ? regular : [idx.get(a[0].name)], hidden ? idx.get(hidden.name) : -1];
}
writeFileSync(new URL("../src/data/abilities.js", import.meta.url),
  "// Generated by tools/fetch-abilities.mjs (npm run abilities) - never edit by hand.\r\n"
  + "// ABILITIES: dex id -> [[regular ability indices], hidden index or -1] into ABILITY_NAMES.\r\n"
  + `export const ABILITY_NAMES = ${JSON.stringify(names)};\r\n`
  + `export const ABILITIES = ${JSON.stringify(rows)};\r\n`);
console.log(`${Object.keys(rows).length} species, ${names.length} abilities; no data for ${missing.length}: ${missing.slice(0, 20).join(", ")}`);
