// Pokemon cries (2026-10-14): PokeAPI's cries repository, the games' own
// "latest" cry per Pokemon. Its ".ogg" files are mostly Vorbis but some are
// MP3, so each is written under its REAL type (Safari will not play an MP3
// served as audio/ogg): public/cries/<id>.ogg or <id>.mp3 for
// every species and every form with a voice of its own, and
// src/data/cries.js: the forms that borrow another's cry (a look, a form
// PokeAPI has no cry for, or one whose cry is its base's byte for byte) and
// the ids that are MP3, so the client never asks for a file that is not there. Cached in
// .assets-src/cries; re-runs fetch nothing they already have.
//
//   npm run cries
import { mkdirSync, existsSync, readFileSync, writeFileSync, copyFileSync } from "node:fs";
import { SPECIES } from "../src/data/dex.js";

const SRC = "https://raw.githubusercontent.com/PokeAPI/cries/main/cries/pokemon/latest";
const CACHE = ".assets-src/cries";
const OUT = "public/cries";
mkdirSync(CACHE, { recursive: true });
mkdirSync(OUT, { recursive: true });

async function fetchCry(id) {
  const file = `${CACHE}/${id}.ogg`;
  if (existsSync(file)) return readFileSync(file);
  if (existsSync(`${file}.none`)) return null;
  const res = await fetch(`${SRC}/${id}.ogg`);
  if (res.status === 404) { writeFileSync(`${file}.none`, ""); return null; }
  if (!res.ok) throw new Error(`cry ${id}: HTTP ${res.status}`);
  const buf = Buffer.from(await res.arrayBuffer());
  writeFileSync(file, buf);
  return buf;
}

const borrow = {};       // form id -> the id whose cry it plays
const mp3 = [];
let n = 0;
for (const sp of SPECIES) {
  // A look is a drawing, never a voice: it is its family's base.
  const own = sp.form === "look" ? null : await fetchCry(sp.id);
  const base = sp.of ?? null;
  if (!own) {
    if (!base) throw new Error(`${sp.name} (${sp.id}) has no cry and no base to borrow one from`);
    borrow[sp.id] = base;
    continue;
  }
  if (base && Buffer.compare(own, await fetchCry(base)) === 0) { borrow[sp.id] = base; continue; }
  const ogg = own.subarray(0, 4).toString("latin1") === "OggS";
  if (!ogg) mp3.push(sp.id);
  copyFileSync(`${CACHE}/${sp.id}.ogg`, `${OUT}/${sp.id}.${ogg ? "ogg" : "mp3"}`);
  n++;
}

writeFileSync("src/data/cries.js", [
  "// Generated by tools/fetch-cries.mjs (npm run cries) - do not edit.",
  "// A form that borrows another's cry: its own id -> the id of the file it plays.",
  "// Every other species has public/cries/<id>.ogg of its own, or .mp3 if listed in CRY_MP3.",
  `export const CRY_OF = ${JSON.stringify(borrow)};`,
  `export const CRY_MP3 = new Set(${JSON.stringify(mp3)});`,
  "",
].join("\r\n"));
console.log(`cries: ${n} files (${mp3.length} MP3), ${Object.keys(borrow).length} forms borrow one`);
